function hideDesktopClass(plugin: string, label: string, className: string) {
    const prefix = className + "_";
    return {
        plugin,
        label,
        css: `[class^="${prefix}"], [class*=" ${prefix}"] { display: none !important; }`,
        desktopOnly: true,
        mobile: [],
        catalogOriginal: true,
    } as const;
}

function hideMobileComponent(plugin: string, label: string, ...paths: string[]) {
    return { plugin, label, css: "", mobileOnly: true, mobile: { hideComponentPaths: paths } } as const;
}

